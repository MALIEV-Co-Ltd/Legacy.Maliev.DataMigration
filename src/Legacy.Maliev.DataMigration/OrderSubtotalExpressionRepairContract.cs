using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace Legacy.Maliev.DataMigration;

/// <summary>Closed preparation and disposable rewrite characterization only; grants no execution authority.</summary>
internal sealed class OrderSubtotalExpressionRepairContract
{
    internal const string SqlServerSourceExpression = "(CONVERT([decimal](18,2),[UnitPrice]*[Quantity]-(([UnitPrice]*[Quantity])*[DiscountPercent])/(100)))";
    // Exact computed-column source metadata, including its expression, represented by digest in the logical plan.
    private const string SourceSubtotalMetadataSha256 = "cc27e69b492190688f090cce1b903bd97819110cd55b2cf6b6c627ce0512e62e";
    internal const string HistoricalExpression = "(((((\"UnitPrice\" * (\"Quantity\")::numeric))::numeric(29,2) - ((((((\"UnitPrice\" * (\"Quantity\")::numeric))::numeric(29,2) * \"DiscountPercent\"))::numeric(35,4) / (100)::numeric))::numeric(38,7)))::numeric(38,6))::numeric(18,2)";
    // Exact corrected translator output pinned by SqlServerMigrationSourceContractTests; never generated by string replacement here.
    internal const string CorrectedExpression = "(((((\"UnitPrice\" * (\"Quantity\")::numeric))::numeric(29,2) - ((((((\"UnitPrice\" * (\"Quantity\")::numeric))::numeric(29,2) * \"DiscountPercent\"))::numeric(35,4) / (100)::numeric(9,6)))::numeric(38,7)))::numeric(38,7))::numeric(18,2)";
    private readonly DatabaseSchemaPlan _before, _after;
    internal string LogicalSourcePlanSha256 { get; }
    internal string SourceCommitSha { get; }
    internal DateTimeOffset SourceCapturedAtUtc { get; }
    internal string ObservedHistoricalExpression { get; }
    internal string ObservedHistoricalExpressionSha256 { get; }
    private readonly string _digest;

    private OrderSubtotalExpressionRepairContract(FreshSchemaPlan logical, DatabaseSchemaPlan before, DatabaseSchemaPlan after,
        string observedHistoricalExpression)
    {
        _before = before; _after = after;
        LogicalSourcePlanSha256 = SchemaPlanCanonicalizer.ComputeSha256(logical);
        SourceCommitSha = logical.SourceCommitSha; SourceCapturedAtUtc = logical.CapturedAtUtc;
        ObservedHistoricalExpression = observedHistoricalExpression;
        ObservedHistoricalExpressionSha256 = Hash(Encoding.UTF8.GetBytes(observedHistoricalExpression));
        _digest = Hash([.. "Legacy.Maliev.OrderSubtotalExpressionRepair.Preparation.v1\0"u8,
            .. JsonSerializer.SerializeToUtf8Bytes(new
            {
                LogicalSourcePlanSha256, SourceCommitSha, SourceCapturedAtUtc, SqlServerSourceExpression,
                HistoricalExpression, CorrectedExpression, ObservedHistoricalExpression, ObservedHistoricalExpressionSha256,
                BeforePhysicalShape = before.TargetSchemaSha256,
                AfterPhysicalShape = after.TargetSchemaSha256, SqlSha256 = Hash(Encoding.UTF8.GetBytes(CandidateSql())),
                Scope = "pure-preparation-and-disposable-characterization-no-execution-authority",
            })]);
    }

    internal static OrderSubtotalExpressionRepairContract Create(FreshSchemaPlan logical, string independentlyExpectedSourceCommitSha,
        string independentlyObservedHistoricalExpression, DateTimeOffset nowUtc)
    {
        ArgumentNullException.ThrowIfNull(logical);
        logical = Clone(logical);
        if (independentlyExpectedSourceCommitSha is not { Length: 40 } ||
            !independentlyExpectedSourceCommitSha.All(char.IsAsciiHexDigitLower) || logical.SourceCommitSha != independentlyExpectedSourceCommitSha ||
            string.IsNullOrWhiteSpace(independentlyObservedHistoricalExpression) || independentlyObservedHistoricalExpression.Length > 8192 ||
            PostgreSqlGeneratedExpressionCanonicalizer.Canonicalize(independentlyObservedHistoricalExpression) !=
                PostgreSqlGeneratedExpressionCanonicalizer.Canonicalize(HistoricalExpression) ||
            SchemaPlanCanonicalizer.Validate(logical, new(logical.SourceCommitSha, new string('0', 64)), nowUtc, TimeSpan.FromHours(2)).Count != 0)
        { throw Invalid(); }
        ProductionSchemaCatalogInspector.ValidatePlan(logical, nowUtc);
        if (!ApprovedConsumerOverlaySelection.IsApproved(logical) || logical.Databases.Sum(x => x.Tables.Count) != 100) { throw Invalid(); }
        DatabaseSchemaPlan order = logical.Databases.Single(x => x.Database == "Order");
        TableCopyPlan root = order.Tables.Single(x => x.SourceSchema == "dbo" && x.SourceTable == "Order" &&
            x.TargetSchema == "public" && x.TargetTable == "Order");
        if (root.SourceColumnTypes.GetValueOrDefault("UnitPrice") != "decimal(18,2)" ||
            root.SourceColumnTypes.GetValueOrDefault("Quantity") != "int" ||
            root.SourceColumnTypes.GetValueOrDefault("DiscountPercent") != "decimal(5,2)" ||
            root.SourceColumnTypes.GetValueOrDefault("Subtotal") != "decimal(18,2)" ||
            root.SourceColumns.Single(x => x.Column == "Subtotal").MetadataSha256 != SourceSubtotalMetadataSha256 ||
            root.ColumnTypes.GetValueOrDefault("UnitPrice") != "numeric(18,2)" || root.ColumnTypes.GetValueOrDefault("Quantity") != "integer" ||
            root.ColumnTypes.GetValueOrDefault("DiscountPercent") != "numeric(5,2)" || root.ColumnTypes.GetValueOrDefault("Subtotal") != "numeric(18,2)" ||
            root.GeneratedColumns.Count(x => x.Column == "Subtotal" && x.Stored && x.Expression == CorrectedExpression) != 1)
        { throw Invalid(); }
        // Physical operand views only: original logical plan and source inventories remain untouched.
        DatabaseSchemaPlan historicalPhysicalPhase = order with { TargetExtensionProfile = ApprovedConsumerOverlaySelection.ProfileForDatabase("Order", ConsumerOverlaySelection.HistoricalDefaults) };
        TableCopyPlan[] afterTables = [.. ApprovedConsumerColumnOverlayManifest.ComposePhysical(historicalPhysicalPhase)];
        TableCopyPlan[] beforeTables = [.. afterTables.Select(table => table.TargetSchema == "public" && table.TargetTable == "Order"
            ? table with { GeneratedColumns = [.. table.GeneratedColumns.Select(column => column.Column == "Subtotal"
                ? column with { Expression = independentlyObservedHistoricalExpression } : column)] } : table)];
        return new(logical, View(order, beforeTables), View(order, afterTables), independentlyObservedHistoricalExpression);
    }

    internal DatabaseSchemaPlan BeforePhysical()
    {
        return Clone(_before);
    }

    internal DatabaseSchemaPlan AfterPhysical()
    {
        return Clone(_after);
    }

    internal string ComputeSha256()
    {
        return _digest;
    }

    internal static string CandidateSql()
    {
        return "SET LOCAL lock_timeout='5s'; SET LOCAL statement_timeout='30s'; " +
            "LOCK TABLE public.\"Order\" IN ACCESS EXCLUSIVE MODE; ALTER TABLE public.\"Order\" ALTER COLUMN \"Subtotal\" SET EXPRESSION AS (" + CorrectedExpression + ");";
    }

    private static DatabaseSchemaPlan View(DatabaseSchemaPlan source, TableCopyPlan[] tables)
    {
        var view = source with { Tables = tables, TargetExtensionProfile = null, SourceDispositionProfile = null, SourceTableDispositions = [] };
        return Clone(view with { TargetSchemaSha256 = PostgreSqlSchemaFingerprint.ComputeExpected(view) });
    }
    private static T Clone<T>(T value)
    {
        return JsonSerializer.Deserialize<T>(JsonSerializer.SerializeToUtf8Bytes(value))!;
    }

    private static string Hash(byte[] value)
    {
        return Convert.ToHexStringLower(SHA256.HashData(value));
    }

    private static MigrationExecutionException Invalid()
    {
        return new("order_subtotal_expression_preparation_invalid",
            "Only the fixed corrected Order Subtotal source contract and exact historical physical preimage are supported.");
    }
}
