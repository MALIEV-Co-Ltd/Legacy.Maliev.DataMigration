namespace Legacy.Maliev.DataMigration.Tests;

[Collection(ConsumerColumnBootstrapTestGroup.Name)]
public sealed class ConsumerColumnBootstrapPreservationNativeTests(ConsumerColumnBootstrapFixture fixture)
{
    [Fact]
    public async Task Read_committed_cannot_supply_a_multi_query_preservation_snapshot()
    {
        FreshSchemaPlan logical = ConsumerColumnBootstrapTestData.Logical();
        var contract = ConsumerColumnBootstrapContract.Create(logical, logical.SourceCommitSha, ConsumerColumnBootstrapTestData.Now);
        using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await using var connection = new NpgsqlConnection(fixture.ConnectionString);
        await connection.OpenAsync(deadline.Token);
        await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.ReadCommitted, deadline.Token);
        MigrationExecutionException failure = await Assert.ThrowsAsync<MigrationExecutionException>(() =>
            ConsumerColumnBootstrapNativePreservation.CaptureAsync(connection, transaction, contract, "CustomerIdentity", false, deadline.Token));
        Assert.Contains("transaction_isolation", failure.Message, StringComparison.Ordinal);
        await transaction.RollbackAsync(deadline.Token);
    }

    [Theory]
    [InlineData("CustomerIdentity", false, false)]
    [InlineData("CustomerIdentity", false, true)]
    [InlineData("CustomerIdentity", true, false)]
    [InlineData("CustomerIdentity", true, true)]
    [InlineData("Quotation", false, false)]
    [InlineData("Quotation", false, true)]
    [InlineData("Quotation", true, false)]
    [InlineData("Quotation", true, true)]
    public async Task Closed_observer_accepts_only_fixed_append_and_characterizes_two_block_retry(string database, bool alphabetical, bool populated)
    {
        FreshSchemaPlan logical = ConsumerColumnBootstrapTestData.Logical();
        var contract = ConsumerColumnBootstrapContract.Create(logical, logical.SourceCommitSha, ConsumerColumnBootstrapTestData.Now);
        ConsumerColumnBootstrapOperand operand = ConsumerColumnBootstrapContract.Operands().Single(x => x.Database == database);
        DatabaseSchemaPlan physical = contract.Before(database);
        if (alphabetical)
        { physical = physical with { Tables = [.. physical.Tables.Select(x => x.TargetSchema == operand.Schema && x.TargetTable == operand.Table ? x with { OrderedColumns = [.. x.OrderedColumns.Order(StringComparer.Ordinal)] } : x)] }; }
        using var deadline = new CancellationTokenSource(TimeSpan.FromMinutes(2)); CancellationToken ct = deadline.Token;
        PostgreSqlShadowTarget target = fixture.CreateShadowTarget();
        ShadowDatabase shadow = await target.CreateUniqueEmptyShadowAsync(database, $"legacy_shadow_bootstrap_guard_{Guid.NewGuid():N}", Guid.NewGuid().ToString("D"), ct);
        ExceptionDispatchInfo? primary = null; Exception? cleanupFailure = null;
        try
        {
            string settings = new NpgsqlConnectionStringBuilder(fixture.ConnectionString) { Database = shadow.Name, Pooling = false }.ConnectionString;
            await using var connection = new NpgsqlConnection(settings); await connection.OpenAsync(ct);
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                await using var schema = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
                await schema.ApplySchemaAsync(physical, ct); await schema.FinalizeSchemaAsync(physical, ct);
                if (populated) { await SeedAsync(connection, transaction, physical.Tables.Single(x => x.TargetSchema == operand.Schema && x.TargetTable == operand.Table), ct); }
                await ExecuteAsync(connection, transaction, """
                    CREATE SCHEMA legacy_migration_internal;
                    CREATE TABLE legacy_migration_internal."BootstrapJournal" ("ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Payload" text NOT NULL);
                    INSERT INTO legacy_migration_internal."BootstrapJournal" ("Payload") VALUES ('synthetic retained journal ไทย  ');
                    """, ct);
                await transaction.CommitAsync(ct);
            }
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                var before = await ConsumerColumnBootstrapNativePreservation.CaptureAsync(connection, transaction, contract, database, false, ct);
                await ExecuteAsync(connection, transaction, ConsumerColumnBootstrapContract.CandidateSql(database), ct);
                var after = await ConsumerColumnBootstrapNativePreservation.CaptureAsync(connection, transaction, contract, database, true, ct);
                ConsumerColumnBootstrapNativePreservation.RequirePreserved(before, after, contract);
                RequireMutationsRejected(before, after, contract);
                await transaction.RollbackAsync(ct);
            }
            ConsumerColumnBootstrapPreservationObservation committedBefore;
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                committedBefore = await ConsumerColumnBootstrapNativePreservation.CaptureAsync(connection, transaction, contract, database, false, ct);
                if (database == "CustomerIdentity")
                {
                    Assert.Equal(2L, committedBefore.Native.Storage("2656").Blocks);
                    Assert.Equal(2L, committedBefore.Native.Storage("2657").Blocks);
                }
                await ExecuteAsync(connection, transaction, ConsumerColumnBootstrapContract.CandidateSql(database), ct);
                var after = await ConsumerColumnBootstrapNativePreservation.CaptureAsync(connection, transaction, contract, database, true, ct);
                ConsumerColumnBootstrapNativePreservation.RequirePreserved(committedBefore, after, contract);
                await transaction.CommitAsync(ct);
            }
            await connection.CloseAsync();
            await using var independent = new NpgsqlConnection(settings); await independent.OpenAsync(ct);
            await using var readback = await independent.BeginTransactionAsync(IsolationLevel.RepeatableRead, ct);
            var observed = await ConsumerColumnBootstrapNativePreservation.CaptureAsync(independent, readback, contract, database, true, ct);
            ConsumerColumnBootstrapNativePreservation.RequirePreserved(committedBefore, observed, contract);
            await readback.RollbackAsync(ct);
        }
        catch (Exception failure) { primary = ExceptionDispatchInfo.Capture(failure); }
        finally
        {
            using var cleanup = new CancellationTokenSource(TimeSpan.FromSeconds(30));
            try { await target.DeleteRunOwnedShadowAsync(shadow, cleanup.Token); } catch (Exception failure) { cleanupFailure = failure; }
        }
        if (cleanupFailure is not null) { throw new AggregateException("Bootstrap observer shadow cleanup failed.", primary is null ? [cleanupFailure] : [primary.SourceException, cleanupFailure]); }
        primary?.Throw();
    }

    private static void RequireMutationsRejected(ConsumerColumnBootstrapPreservationObservation before,
        ConsumerColumnBootstrapPreservationObservation after, ConsumerColumnBootstrapContract contract)
    {
        ConsumerColumnBootstrapOperand operand = ConsumerColumnBootstrapContract.Operands().Single(x => x.Database == after.LogicalDatabase);
        RejectRaw("pg_attribute", rows => rows.Single(x => x["attname"]?.ToString() == operand.Column)["atttypid"] = "25");
        RejectRaw("pg_attribute", rows => rows.Single(x => x["attname"]?.ToString() == operand.Column)["attcollation"] = "100");
        RejectRaw("pg_attribute", rows => rows.Single(x => x["attname"]?.ToString() == operand.Column)["attoptions"] = new JsonArray("pg_attver=0"));
        RejectRaw("pg_attribute", rows => rows.Single(x => x["attname"]?.ToString() == operand.Column)["attoptions"] = new JsonArray("pg_attver=1", "n_distinct=-0.25"));
        RejectRaw("pg_attribute", rows =>
        {
            string table = rows.Single(x => x["attname"]?.ToString() == operand.Column)["attrelid"]!.ToString();
            rows.Single(x => x["attrelid"]?.ToString() == table && x["attnum"]?.ToString() == "1")["attoptions"] = new JsonArray("pg_attver=1");
        });
        _ = Assert.Throws<MigrationExecutionException>(() => ConsumerColumnBootstrapNativePreservation.RequirePreserved(before, after with { WalUpper = before.WalUpper }, contract));
        _ = Assert.Throws<MigrationExecutionException>(() => ConsumerColumnBootstrapNativePreservation.RequirePreserved(before, after with { CompositeDefense = "warning" }, contract));
        RejectRaw("pg_namespace", rows => rows.Add((JsonObject)rows[0].DeepClone()));
        RejectRaw("pg_statistic", rows => rows.Add(new JsonObject { ["starelid"] = "999999" }));
        RejectRaw("pg_index", rows => rows[0]["indisvalid"] = false);
        if (!operand.Nullable)
        {
            string table = after.Native.Read("pg_attribute").Single(x => x["attname"]?.ToString() == operand.Column)["attrelid"]!.ToString();
            RejectRaw("pg_attrdef", rows => rows.Single(x => x["adrelid"]?.ToString() == table && x["adnum"]?.ToString() == "19")["adbin"] = "unexpected");
            RejectRaw("pg_attrdef", rows => rows.Single(x => x["adrelid"]?.ToString() == table && x["adnum"]?.ToString() == "19")["oid"] = "999999");
            RejectRaw("pg_depend", rows => rows.Add((JsonObject)rows.First(x => x["refobjid"]?.ToString() == table && x["refobjsubid"]?.ToString() == "19").DeepClone()));
        }
        _ = Assert.Throws<MigrationExecutionException>(() => ConsumerColumnBootstrapNativePreservation.RequirePreserved(before,
            after with { OriginalRows = after.OriginalRows with { RowSha256 = new string('0', 64) } }, contract));
        RejectSnapshot(after.Native.Snapshot with
        { Relations = [.. after.Native.Snapshot.Relations.Select(x => x.Schema == "legacy_migration_internal" ? x with { Rows = x.Rows + 1 } : x)] });
        RejectSnapshot(after.Native.Snapshot with { Sequences = [.. after.Native.Snapshot.Sequences.Select(x => x with { TupleSha256 = new string('0', 64) })] });
        var storage = IndexStorage(after.Native); string index = storage.Keys.First(); storage[index] = (storage[index].FileNode + 1, storage[index].Blocks);
        var replaced = new CurrentAppOwnedRetained31Observation(after.Native.Snapshot, Tuples(after.Native), storage);
        _ = Assert.Throws<MigrationExecutionException>(() => ConsumerColumnBootstrapNativePreservation.RequirePreserved(before, after with { Native = replaced }, contract));

        void RejectRaw(string catalog, Action<List<JsonObject>> mutate)
        {
            var tuples = Tuples(after.Native); var rows = tuples[catalog].Select(x => JsonNode.Parse(x)!.AsObject()).ToList(); mutate(rows);
            tuples[catalog] = rows.Select(x => x.ToJsonString()).ToArray();
            var changed = new CurrentAppOwnedRetained31Observation(after.Native.Snapshot, tuples, IndexStorage(after.Native));
            _ = Assert.Throws<MigrationExecutionException>(() => ConsumerColumnBootstrapNativePreservation.RequirePreserved(before, after with { Native = changed }, contract));
        }
        void RejectSnapshot(CurrentAppOwnedDatabaseSnapshot snapshot)
        {
            var changed = new CurrentAppOwnedRetained31Observation(snapshot, Tuples(after.Native), IndexStorage(after.Native));
            _ = Assert.Throws<MigrationExecutionException>(() => ConsumerColumnBootstrapNativePreservation.RequirePreserved(before, after with { Native = changed }, contract));
        }
    }

    private static Dictionary<string, string[]> Tuples(CurrentAppOwnedRetained31Observation native)
    {
        return ConsumerColumnBootstrapNativePreservation.CatalogNames.ToDictionary(x => x, x => native.Read(x).Select(row => row.ToJsonString()).ToArray(), StringComparer.Ordinal);
    }

    private static Dictionary<string, (uint FileNode, long Blocks)> IndexStorage(CurrentAppOwnedRetained31Observation native)
    {
        return native.Read("pg_class").Where(x => x["relkind"]?.ToString() == "i").ToDictionary(x => x["oid"]!.ToString(), x => native.Storage(x["oid"]!.ToString()), StringComparer.Ordinal);
    }

    private static async Task SeedAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, TableCopyPlan root, CancellationToken ct)
    {
        string[] names = [.. root.OrderedColumns.Except(root.GeneratedColumns.Select(x => x.Column), StringComparer.Ordinal)];
        await using var command = new NpgsqlCommand("INSERT INTO public." + PostgreSqlShadowTarget.QuoteIdentifier(root.TargetTable) + " (" +
            string.Join(',', names.Select(PostgreSqlShadowTarget.QuoteIdentifier)) + ") VALUES (" + string.Join(',', Enumerable.Range(1, names.Length).Select(x => "$" + x)) + ");", connection, transaction)
        { CommandTimeout = 30 };
        foreach (string column in names)
        {
            object? value = root.NullableColumns.Contains(column, StringComparer.Ordinal) ? null : root.ColumnTypes[column] switch
            {
                "integer" => 1,
                "boolean" => false,
                "numeric(18,2)" => 1m,
                "timestamp without time zone" => new DateTime(2000, 1, 1, 0, 0, 0, DateTimeKind.Unspecified),
                _ when root.ColumnTypes[column] == "text" || root.ColumnTypes[column].StartsWith("character varying(", StringComparison.Ordinal) => "s1 ไทย  ",
                _ => throw new InvalidOperationException("Unreviewed synthetic seed type."),
            };
            _ = command.Parameters.AddWithValue(value ?? DBNull.Value);
        }
        _ = await command.ExecuteNonQueryAsync(ct);
    }
    private static async Task ExecuteAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, string sql, CancellationToken ct)
    { await using var command = new NpgsqlCommand(sql, connection, transaction) { CommandTimeout = 30 }; _ = await command.ExecuteNonQueryAsync(ct); }
}
