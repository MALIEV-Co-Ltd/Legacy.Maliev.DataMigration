    private sealed class NativeEnvironment(string connectionString, CurrentAppOwnedRepairScope scope,
        CurrentAppOwnedDatabaseSnapshot baseline, CommitAcknowledgementProxy proxy) : ICurrentAppOwnedRepairEnvironment
    {
        internal Dictionary<string, byte[]> Evidence { get; } = new(StringComparer.Ordinal);
        internal int DuplicateEvidenceAttempts { get; private set; }
        internal byte[]? RejectedEvidence { get; private set; }
        private bool _armAtFinalRecheck;
        public Task RequireSourceAsync(string sourceCommitSha, CancellationToken cancellationToken)
        { Assert.Equal(scope.SourceCommitSha, sourceCommitSha); return Task.CompletedTask; }
        public Task RequireResourceAndCustodyAsync(CurrentAppOwnedRepairScope current, CancellationToken cancellationToken)
        {
            Assert.Equal(JsonSerializer.Serialize(scope), JsonSerializer.Serialize(current));
            // The executor's final admission recheck follows prepared publication;
            // only its installed-policy SELECT remains before the real COMMIT.
            if (_armAtFinalRecheck) { proxy.Arm(); _armAtFinalRecheck = false; }
            return Task.CompletedTask;
        }
        public async Task<string> InspectGlobalPreservationAsync(CancellationToken cancellationToken)
        {
            await using var connection = new NpgsqlConnection(connectionString);
            await connection.OpenAsync(cancellationToken);
            await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.RepeatableRead, cancellationToken);
            await using var readOnly = new NpgsqlCommand("SET TRANSACTION READ ONLY;", connection, transaction);
            _ = await readOnly.ExecuteNonQueryAsync(cancellationToken);
            await PostgreSqlCurrentAppOwnedEightRepair.RequireInstalledPolicyAsync(connection, transaction, scope, cancellationToken);
            CurrentAppOwnedDatabaseSnapshot observed = await CurrentAppOwnedRepairPreservation.CaptureAsync(connection, transaction, cancellationToken);
            string[] names = CurrentAppOwnedRepairManifest.NewTables("Customer");
            string[] present = [.. observed.Relations.Where(item => item.Schema == "public" && names.Contains(item.Name, StringComparer.Ordinal)).Select(item => item.Name)];
            IReadOnlySet<string> closure = present.Length == 0 ? new HashSet<string>() :
                await CurrentAppOwnedRepairPreservation.ObserveNewObjectClosureAsync(connection, transaction, "Customer", "legacy_local", cancellationToken);
            CurrentAppOwnedRepairPreservation.RequirePreserved(baseline, observed, closure, present);
            return scope.GlobalPreservationSha256;
        }
        public Task RetainNewEvidenceAsync(string name, byte[] payload, CancellationToken cancellationToken)
        {
            if (!Evidence.TryAdd(name, payload.ToArray()))
            { DuplicateEvidenceAttempts++; RejectedEvidence = payload.ToArray(); throw CurrentAppOwnedRepairPermit.Invalid(); }
            if (name.EndsWith("-prepared.json", StringComparison.Ordinal)) { _armAtFinalRecheck = true; }
            return Task.CompletedTask;
        }
    }

    // Plain PostgreSQL protocol only, restricted to this test's loopback listener.
    // CommandComplete(COMMIT) is generated after the server commits. Drop that
    // entire packet and close both sockets before notifying the test observer.
    private sealed class CommitAcknowledgementProxy : IAsyncDisposable
    {
        private readonly TcpListener _listener = new(IPAddress.Loopback, 0);
        private readonly CancellationTokenSource _lifetime = new(TimeSpan.FromMinutes(3));
        private readonly TaskCompletionSource _dropped = new(TaskCreationOptions.RunContinuationsAsynchronously);
        private readonly Task _worker;
        private int _armed;
        private int _droppedCommits;
        internal int Port { get; }
        internal Task Dropped => _dropped.Task;
        internal int DroppedCommits => Volatile.Read(ref _droppedCommits);
        internal void Arm()
        {
            _ = Interlocked.Exchange(ref _armed, 1);
        }

        internal CommitAcknowledgementProxy(string upstreamHost, int upstreamPort)
        {
            _listener.Start(1);
            Port = ((IPEndPoint)_listener.LocalEndpoint).Port;
            _worker = RunAsync(upstreamHost, upstreamPort);
        }
        private async Task RunAsync(string host, int port)
        {
            try
            {
                while (!_lifetime.IsCancellationRequested)
                {
                    using TcpClient client = await _listener.AcceptTcpClientAsync(_lifetime.Token);
                    using var server = new TcpClient();
                    await server.ConnectAsync(host, port, _lifetime.Token);
                    using var session = CancellationTokenSource.CreateLinkedTokenSource(_lifetime.Token);
                    Task frontend = client.GetStream().CopyToAsync(server.GetStream(), session.Token);
                    Task backend = RelayBackendAsync(server.GetStream(), client.GetStream(), session.Token);
                    try { _ = await Task.WhenAny(frontend, backend); }
                    finally
                    {
                        await session.CancelAsync();
                        client.Close(); server.Close();
                        try { await Task.WhenAll(frontend, backend); }
                        catch (Exception exception) when (exception is IOException or SocketException or OperationCanceledException or ObjectDisposedException) { }
                        if (DroppedCommits > 0) { _ = _dropped.TrySetResult(); }
                    }
                }
            }
            catch (Exception exception) when (_lifetime.IsCancellationRequested &&
                exception is OperationCanceledException or SocketException or ObjectDisposedException)
            { }
        }
        private async Task RelayBackendAsync(NetworkStream server, NetworkStream client, CancellationToken ct)
        {
            byte[] header = new byte[5];
            while (true)
            {
                int first = await server.ReadAsync(header.AsMemory(0, 1), ct);
                if (first == 0) { return; }
                await server.ReadExactlyAsync(header.AsMemory(1, 4), ct);
                int length = BinaryPrimitives.ReadInt32BigEndian(header.AsSpan(1));
                if (length is < 4 or > 16 * 1024 * 1024) { throw new InvalidDataException("Invalid PostgreSQL frame in owned test proxy."); }
                byte[] payload = new byte[length - 4];
                await server.ReadExactlyAsync(payload, ct);
                if (header[0] == (byte)'C' && payload.AsSpan().SequenceEqual("COMMIT\0"u8) &&
                    Interlocked.CompareExchange(ref _armed, 0, 1) == 1)
                { _ = Interlocked.Increment(ref _droppedCommits); return; }
                await client.WriteAsync(header, ct);
                await client.WriteAsync(payload, ct);
            }
        }
        public async ValueTask DisposeAsync()
        {
            await _lifetime.CancelAsync();
            _listener.Stop();
            try { await _worker.WaitAsync(TimeSpan.FromSeconds(10)); }
            finally { _lifetime.Dispose(); }
            Assert.True(_worker.IsCompleted);
        }
    }
