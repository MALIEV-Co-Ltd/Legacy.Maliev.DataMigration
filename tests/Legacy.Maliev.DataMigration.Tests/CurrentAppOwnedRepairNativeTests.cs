using System.Data;
using Npgsql;
using Testcontainers.PostgreSql;

namespace Legacy.Maliev.DataMigration.Tests;

[Collection(LocalSnapshotIoTestGroup.Name)]
public sealed class CurrentAppOwnedRepairNativeTests
{
    [Theory]
    [InlineData("Customer")]
    [InlineData("Order")]
    [InlineData("Upload")]
    public async Task Native_fixed_ddl_preserves_retained_rows_catalog_and_sequences_across_rollback_and_commit(string database)
    {
        await using var postgres = new PostgreSqlBuilder(
            "postgres:18.4-bookworm@sha256:882236b897e39051d2368c5ccc6cda944904723506b2dfc97f2a8f5bc9afa382")
            .WithDatabase(database).WithUsername("postgres").WithPassword(Guid.NewGuid().ToString("N"))
            .WithCreateParameterModifier(parameters =>
            {
                parameters.HostConfig!.Memory = 384 * 1024 * 1024;
                parameters.HostConfig.MemorySwap = 384 * 1024 * 1024;
                parameters.HostConfig.NanoCPUs = 500_000_000;
            }).Build();
        await postgres.StartAsync();
        await using var connection = new NpgsqlConnection(postgres.GetConnectionString());
        await connection.OpenAsync();
        DatabaseSchemaPlan beforeSchema = CurrentConsumerSchemaV2Tests.Schema(ConsumerOverlaySelection.CurrentConsumerColumnsV1)
            .Databases.Single(plan => plan.Database == database);
        DatabaseSchemaPlan afterSchema = CurrentConsumerSchemaV2Tests.Schema(ConsumerOverlaySelection.CurrentConsumerSchemaV2)
            .Databases.Single(plan => plan.Database == database);
        await using (var setup = await connection.BeginTransactionAsync())
        {
            await using var inspector = new PostgreSqlWholeDatabaseTransaction(connection, setup, ownsResources: false);
            await inspector.ApplySchemaAsync(beforeSchema, CancellationToken.None);
            await inspector.FinalizeSchemaAsync(beforeSchema, CancellationToken.None);
            await ExecuteAsync("""
                CREATE SCHEMA legacy_migration_internal;
                CREATE TABLE legacy_migration_internal.retained (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text NOT NULL);
                INSERT INTO legacy_migration_internal.retained(value) VALUES ('synthetic Thai fixture กขค'), ('synthetic retained receipt');
                ANALYZE legacy_migration_internal.retained;
                """, setup);
            await setup.CommitAsync();
        }

        CurrentAppOwnedDatabaseSnapshot baseline = await CaptureAsync();
        await using (var rollback = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
        {
            _ = await RepairAndCheckAsync(rollback, baseline);
            await rollback.RollbackAsync();
        }
        CurrentAppOwnedDatabaseSnapshot rolledBack = await CaptureAsync();
        Assert.Equal(baseline.Sha256, rolledBack.Sha256);
        CurrentAppOwnedRepairPreservation.RequirePreserved(baseline, rolledBack, new HashSet<string>(), []);

        await using (var rejected = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
        {
            _ = await Assert.ThrowsAsync<MigrationExecutionException>(() =>
                RepairAndCheckAsync(rejected, baseline, mutateRetainedRow: true));
            await rejected.RollbackAsync();
        }
        Assert.Equal(baseline.Sha256, (await CaptureAsync()).Sha256);

        CurrentAppOwnedDatabaseSnapshot committed;
        await using (var apply = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
        {
            committed = await RepairAndCheckAsync(apply, baseline);
            await apply.CommitAsync();
        }
        CurrentAppOwnedDatabaseSnapshot readback = await CaptureAsync();
        Assert.Equal(committed.Sha256, readback.Sha256);
        CurrentAppOwnedRepairPreservation.RequirePreserved(committed, readback, new HashSet<string>(), []);

        async Task<CurrentAppOwnedDatabaseSnapshot> RepairAndCheckAsync(NpgsqlTransaction transaction,
            CurrentAppOwnedDatabaseSnapshot before, bool mutateRetainedRow = false)
        {
            await CurrentAppOwnedRepairPreservation.LockAsync(connection, transaction, before, CancellationToken.None);
            await ExecuteAsync(CurrentAppOwnedRepairManifest.CreateEightSql(database), transaction);
            await using var inspector = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
            Assert.Equal(afterSchema.TargetSchemaSha256,
                await inspector.InspectSchemaAsync(afterSchema, CancellationToken.None));
            IReadOnlySet<string> closure = await CurrentAppOwnedRepairPreservation.ObserveNewObjectClosureAsync(
                connection, transaction, database, "postgres", CancellationToken.None);
            if (mutateRetainedRow)
            {
                await ExecuteAsync("UPDATE legacy_migration_internal.retained SET value='synthetic unapproved change' WHERE id=1;",
                    transaction);
            }
            CurrentAppOwnedDatabaseSnapshot after = await CurrentAppOwnedRepairPreservation.CaptureAsync(
                connection, transaction, CancellationToken.None);
            CurrentAppOwnedRepairPreservation.RequirePreserved(before, after, closure,
                CurrentAppOwnedRepairManifest.NewTables(database));
            return after;
        }

        async Task<CurrentAppOwnedDatabaseSnapshot> CaptureAsync()
        {
            await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.RepeatableRead);
            await ExecuteAsync("SET TRANSACTION READ ONLY;", transaction);
            return await CurrentAppOwnedRepairPreservation.CaptureAsync(connection, transaction, CancellationToken.None);
        }

        async Task ExecuteAsync(string sql, NpgsqlTransaction transaction)
        {
            await using var command = new NpgsqlCommand(sql, connection, transaction);
            _ = await command.ExecuteNonQueryAsync();
        }
    }
}
