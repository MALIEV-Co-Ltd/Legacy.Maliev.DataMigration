    // Source/owner/custody checks below are deliberately supplied component seams.
    // Installed role/HBA/system identity and complete native fleet observations are real.
    private sealed class NativeEnvironment(string op, string ordinary, CurrentAuthRepairScope scope, FreshSchemaPlan source,
        IReadOnlyList<CurrentAppOwnedDatabaseSnapshot> baseline, CurrentAuthNativeObservation nativeBefore,
        CommitAcknowledgementProxy? proxy, string fault, CurrentAuthExecutedProofRecorder? proof = null) : ICurrentAuthRepairEnvironment, ICurrentAuthNativeProofObserver
    {
        private bool _reserved, _arm;
        private readonly Lock _gate = new();
        internal int Reservations { get; private set; }
        internal string AuthorizationSha256 { get; set; } = string.Empty;
        internal Dictionary<string, byte[]> Evidence { get; } = new(StringComparer.Ordinal);
        public Task RequireSourceAsync(string commit, CancellationToken ct)
        {
            return commit == scope.SourceCommitSha ? Task.CompletedTask : throw CurrentAuthRepairPermit.Invalid();
        }

        public Task RequireAuthOwnerSourceAsync(CurrentAuthRepairScope current, CancellationToken ct)
        {
            return current.AuthOwnerCommitSha != ApprovedCurrentAuthSchema.AuthServiceCommit || current.AuthOwnerSourcePinsSha256 != CurrentAuthRepairPermit.OwnerPinsSha256
                ? throw CurrentAuthRepairPermit.Invalid()
                : Task.CompletedTask;
        }
        public Task RequireSource23PhysicalBaselineAsync(FreshSchemaPlan supplied, CancellationToken ct)
        {
            return SchemaPlanCanonicalizer.ComputeSha256(supplied) != SchemaPlanCanonicalizer.ComputeSha256(source)
                ? throw CurrentAuthRepairPermit.Invalid()
                : Task.CompletedTask;
        }
        public async Task RequireResourceAndCustodyAsync(CurrentAuthRepairScope current, CancellationToken ct)
        {
            if (JsonSerializer.Serialize(current) != JsonSerializer.Serialize(scope)) { throw CurrentAuthRepairPermit.Invalid(); }
            foreach (string database in scope.BeforeDatabaseSha256.Keys)
            {
                bool rejected = false;
                try { await using var probe = new NpgsqlConnection(new NpgsqlConnectionStringBuilder(ordinary) { Database = database }.ConnectionString); await probe.OpenAsync(ct); }
                catch (PostgresException failure) when (failure.SqlState == "28000") { rejected = true; }
                if (!rejected) { throw CurrentAuthRepairPermit.Invalid(); }
            }
            if (proof is not null) { await proof.RecordAsync("ordinary-rejections", scope.BeforeDatabaseSha256.Keys.Order(StringComparer.Ordinal).ToArray(), ct); }
            if (_arm) { proxy?.Arm(); _arm = false; }
        }
        public async Task<IReadOnlyList<CurrentAppOwnedDatabaseSnapshot>> InspectFleetAsync(CurrentAuthRepairScope current, CancellationToken ct)
        {
            if (JsonSerializer.Serialize(current) != JsonSerializer.Serialize(scope)) { throw CurrentAuthRepairPermit.Invalid(); }
            await using (var connection = new NpgsqlConnection(op))
            {
                await connection.OpenAsync(ct);
                await using var query = new NpgsqlCommand("SELECT datname FROM pg_database WHERE NOT datistemplate AND datallowconn ORDER BY datname COLLATE \"C\";", connection);
                var names = new List<string>(); await using var reader = await query.ExecuteReaderAsync(ct);
                while (await reader.ReadAsync(ct)) { names.Add(reader.GetString(0)); }
                Assert.Equal(scope.BeforeDatabaseSha256.Keys.Order(StringComparer.Ordinal), names);
            }
            var pool = new CurrentAppOwnedSnapshotInternPool(); var actual = new List<CurrentAppOwnedDatabaseSnapshot>(); var physicalReadback = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (CurrentAppOwnedDatabaseSnapshot expected in baseline)
            {
                await using var connection = new NpgsqlConnection(new NpgsqlConnectionStringBuilder(op) { Database = expected.Database }.ConnectionString);
                await connection.OpenAsync(ct); await using var tx = await connection.BeginTransactionAsync(IsolationLevel.RepeatableRead, ct);
                await Sql(connection, tx, "SET TRANSACTION READ ONLY;", ct);
                await PostgreSqlCurrentAuthRepair.RequireInstalledPolicyAsync(connection, tx, scope, ct);
                CurrentAppOwnedDatabaseSnapshot snapshot;
                if (expected.Database == "Auth")
                {
                    CurrentAuthNativeObservation auth = await CurrentAuthNativePreservation.CaptureAsync(connection, tx, ct);
                    snapshot = pool.Intern(auth.Snapshot);
                    if (snapshot.Sha256 == scope.BeforeDatabaseSha256["Auth"]) { CurrentAuthNativePreservation.RequireBefore(auth); }
                    else
                    {
                        CurrentAuthRepairReceipt prepared = Receipt("prepared");
                        if (prepared.AfterSha256 != snapshot.Sha256) { throw CurrentAuthRepairPermit.Invalid(); }
                        CurrentAuthNativePreservation.RequirePreserved(nativeBefore, auth);
                    }
                }
                else
                {
                    snapshot = pool.Intern(await CurrentAppOwnedRepairPreservation.CaptureAsync(connection, tx, ct));
                    Assert.Equal(expected.Sha256, snapshot.Sha256);
                    if (DatabaseInventory.ActiveDatabases.Contains(expected.Database, StringComparer.Ordinal))
                    {
                        DatabaseSchemaPlan physical = source.Databases.Single(x => x.Database == expected.Database);
                        await using var inspector = new PostgreSqlWholeDatabaseTransaction(connection, tx, ownsResources: false);
                        string observedSchema = await inspector.InspectSchemaAsync(physical, ct);
                        Assert.Equal(physical.TargetSchemaSha256, observedSchema); physicalReadback.Add(expected.Database, observedSchema);
                    }
                }
                actual.Add(snapshot); await tx.RollbackAsync(ct);
            }
            if (proof is not null) { await proof.RecordAsync("source-physical", physicalReadback, ct); await proof.CapacityAsync(admission: false, ct); }
            return actual.AsReadOnly();
        }
        public Task RequireFreshOperationAsync(CurrentAuthRepairScope current, CancellationToken ct)
        {
            return _reserved || Evidence.Count != 0 ? throw CurrentAuthRepairPermit.Invalid() : Task.CompletedTask;
        }

        public Task ReserveFreshOperationAsync(CurrentAuthRepairScope current, string authorization, CancellationToken ct)
        {
            lock (_gate)
            {
                if (_reserved || Evidence.Count != 0 || authorization != AuthorizationSha256) { throw CurrentAuthRepairPermit.Invalid(); }
