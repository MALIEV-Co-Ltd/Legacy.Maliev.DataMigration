using System.Data;
using System.Runtime.ExceptionServices;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Npgsql;
using Xunit.Abstractions;

namespace Legacy.Maliev.DataMigration.Tests;

[Collection(ConsumerColumnBootstrapTestGroup.Name)]
public sealed class ConsumerColumnBootstrapNativeTests(ConsumerColumnBootstrapFixture fixture, ITestOutputHelper output)
{
    [Theory]
    [InlineData("CustomerIdentity", false, false)]
    [InlineData("CustomerIdentity", false, true)]
    [InlineData("CustomerIdentity", true, false)]
    [InlineData("CustomerIdentity", true, true)]
    [InlineData("Quotation", false, false)]
    [InlineData("Quotation", false, true)]
    [InlineData("Quotation", true, false)]
    [InlineData("Quotation", true, true)]
    public async Task Fixed_append_is_measured_with_rollback_and_independent_readback(string database, bool alphabetical, bool populated)
    {
        FreshSchemaPlan logical = ConsumerColumnBootstrapTestData.Logical();
        string logicalBytes = JsonSerializer.Serialize(logical);
        string logicalHash = SchemaPlanCanonicalizer.ComputeSha256(logical);
        var contract = ConsumerColumnBootstrapContract.Create(logical, logical.SourceCommitSha, ConsumerColumnBootstrapTestData.Now);
        ConsumerColumnBootstrapOperand operand = ConsumerColumnBootstrapContract.Operands().Single(x => x.Database == database);
        TableCopyPlan root = contract.Before(database).Tables.Single(x => x.TargetSchema == operand.Schema && x.TargetTable == operand.Table);
        TableCopyPlan physicalRoot = alphabetical ? root with { OrderedColumns = [.. root.OrderedColumns.Order(StringComparer.Ordinal)] } : root;
        TableCopyPlan unrelated = new("target-only", "BootstrapUnrelated", "public", "BootstrapUnrelated", ["ID", "Payload"], ["ID"])
        {
            ColumnTypes = new Dictionary<string, string>(StringComparer.Ordinal) { ["ID"] = "integer", ["Payload"] = "text" },
            PrimaryKey = new("PK_BootstrapUnrelated", ["ID"]),
            Indexes = [new("IX_BootstrapUnrelated_Payload", ["Payload"], false)],
        };
        // Detached selected-table test inventories, not alternate source plans or complete target schema acceptance.
        DatabaseSchemaPlan beforeFixture = contract.Before(database) with { Tables = [physicalRoot, unrelated] };
        beforeFixture = beforeFixture with { TargetSchemaSha256 = PostgreSqlSchemaFingerprint.ComputeExpected(beforeFixture) };
        TableCopyPlan afterRoot = contract.After(database).Tables.Single(x => x.TargetSchema == operand.Schema && x.TargetTable == operand.Table)
            with
        { OrderedColumns = [.. physicalRoot.OrderedColumns, operand.Column] };
        DatabaseSchemaPlan afterFixture = contract.After(database) with { Tables = [afterRoot, unrelated] };
        afterFixture = afterFixture with { TargetSchemaSha256 = PostgreSqlSchemaFingerprint.ComputeExpected(afterFixture) };

        using var deadline = new CancellationTokenSource(TimeSpan.FromMinutes(2));
        CancellationToken ct = deadline.Token;
        PostgreSqlShadowTarget target = fixture.CreateShadowTarget();
        ShadowDatabase shadow = await target.CreateUniqueEmptyShadowAsync(database,
            $"legacy_shadow_consumer_columns_{Guid.NewGuid():N}", Guid.NewGuid().ToString("D"), ct);
        ExceptionDispatchInfo? primary = null; Exception? cleanupFailure = null;
        try
        {
            string connectionString = new NpgsqlConnectionStringBuilder(fixture.ConnectionString) { Database = shadow.Name, Pooling = false }.ConnectionString;
            await using var connection = new NpgsqlConnection(connectionString);
            await connection.OpenAsync(ct);
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                await using var schema = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
                await schema.ApplySchemaAsync(beforeFixture, ct);
                await schema.FinalizeSchemaAsync(beforeFixture, ct);
                if (populated)
                {
                    await InsertAsync(connection, transaction, root, 1, ct);
                    await InsertAsync(connection, transaction, root, 2, ct);
                }
                await ExecuteAsync(connection, transaction, """
                    INSERT INTO public."BootstrapUnrelated" VALUES (1,'synthetic unrelated ไทย  ');
                    CREATE SCHEMA legacy_migration_internal;
                    CREATE TABLE legacy_migration_internal."BootstrapJournal" ("ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Payload" text NOT NULL);
                    INSERT INTO legacy_migration_internal."BootstrapJournal" ("Payload") VALUES ('synthetic immutable journal  ');
                    """, ct);
                Assert.Equal(beforeFixture.TargetSchemaSha256, await schema.InspectSchemaAsync(beforeFixture, ct));
                await transaction.CommitAsync(ct);
            }

            ConsumerColumnBootstrapNativeObservation baseline;
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                baseline = await ConsumerColumnBootstrapNativeObservations.CaptureAsync(connection, transaction, operand, false, ct);
                await ExecuteAsync(connection, transaction, ConsumerColumnBootstrapContract.CandidateSql(database), ct);
                var changed = await ConsumerColumnBootstrapNativeObservations.CaptureAsync(connection, transaction, operand, true, ct);
                ConsumerColumnBootstrapNativeObservations.RequireOriginalDataAndObjects(baseline, changed, operand);
                ConsumerColumnBootstrapNativeObservations.Report(output, baseline, changed, operand, "prepared-rollback");
                await RequireAfterAsync(connection, transaction, afterFixture, operand, ct);
                await transaction.RollbackAsync(ct);
            }
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.RepeatableRead, ct))
            {
                var rolledBack = await ConsumerColumnBootstrapNativeObservations.CaptureAsync(connection, transaction, operand, false, ct);
                Assert.Equal(baseline.Native.Snapshot.Sha256, rolledBack.Native.Snapshot.Sha256);
                ConsumerColumnBootstrapNativeObservations.RequireOriginalDataAndObjects(baseline, rolledBack, operand);
                await transaction.RollbackAsync(ct);
            }
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                var immediate = await ConsumerColumnBootstrapNativeObservations.CaptureAsync(connection, transaction, operand, false, ct);
                Assert.Equal(baseline.Native.Snapshot.Sha256, immediate.Native.Snapshot.Sha256);
                await ExecuteAsync(connection, transaction, ConsumerColumnBootstrapContract.CandidateSql(database), ct);
                var changed = await ConsumerColumnBootstrapNativeObservations.CaptureAsync(connection, transaction, operand, true, ct);
                ConsumerColumnBootstrapNativeObservations.RequireOriginalDataAndObjects(baseline, changed, operand);
                ConsumerColumnBootstrapNativeObservations.Report(output, baseline, changed, operand, "prepared-commit");
                await RequireAfterAsync(connection, transaction, afterFixture, operand, ct);
                await transaction.CommitAsync(ct);
            }
            await connection.CloseAsync();
            await using var readback = new NpgsqlConnection(connectionString);
            await readback.OpenAsync(ct);
            await using (var transaction = await readback.BeginTransactionAsync(IsolationLevel.RepeatableRead, ct))
            {
                var observed = await ConsumerColumnBootstrapNativeObservations.CaptureAsync(readback, transaction, operand, true, ct);
                ConsumerColumnBootstrapNativeObservations.RequireOriginalDataAndObjects(baseline, observed, operand);
                ConsumerColumnBootstrapNativeObservations.Report(output, baseline, observed, operand, "independent-commit-readback");
                await RequireAfterAsync(readback, transaction, afterFixture, operand, ct);
                await transaction.RollbackAsync(ct);
            }
            // Future INSERT behavior is tested separately and rolled back; no new row is included in preservation evidence.
            await using (var transaction = await readback.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                await InsertAsync(readback, transaction, root, 9, ct);
                await ConsumerColumnBootstrapNativeObservations.RequireNewColumnValuesAsync(readback, transaction, operand, ct);
                await transaction.RollbackAsync(ct);
            }
            Assert.Equal(logicalBytes, JsonSerializer.Serialize(logical));
            Assert.Equal(logicalHash, SchemaPlanCanonicalizer.ComputeSha256(logical));
            Assert.Equal(logicalHash, contract.LogicalSourcePlanSha256);
        }
        catch (Exception failure) { primary = ExceptionDispatchInfo.Capture(failure); }
        finally
        {
            using var cleanup = new CancellationTokenSource(TimeSpan.FromSeconds(30));
            try { await target.DeleteRunOwnedShadowAsync(shadow, cleanup.Token); }
            catch (Exception failure) { cleanupFailure = failure; }
        }
        if (cleanupFailure is not null)
        { throw new AggregateException("Bootstrap characterization could not delete its exact owned shadow.", primary is null ? [cleanupFailure] : [primary.SourceException, cleanupFailure]); }
        primary?.Throw();
    }

    private static async Task RequireAfterAsync(NpgsqlConnection connection, NpgsqlTransaction transaction,
        DatabaseSchemaPlan fixturePlan, ConsumerColumnBootstrapOperand operand, CancellationToken ct)
    {
        await using var inspector = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
        Assert.Equal(fixturePlan.TargetSchemaSha256, await inspector.InspectSchemaAsync(fixturePlan, ct));
        await ConsumerColumnBootstrapNativeObservations.RequireNewColumnValuesAsync(connection, transaction, operand, ct);
        await using var column = new NpgsqlCommand("""
            SELECT a.attnum, format_type(a.atttypid,a.atttypmod), a.attnotnull, a.atthasdef, a.atthasmissing,
                a.attmissingval::text, pg_get_expr(d.adbin,d.adrelid),
                (SELECT count(*) FROM pg_constraint k WHERE k.conrelid=c.oid AND k.contype='n' AND k.conkey=ARRAY[a.attnum])
            FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
            WHERE n.nspname=$1 AND c.relname=$2 AND a.attname=$3 AND NOT a.attisdropped;
            """, connection, transaction) { CommandTimeout = 30 };
        _ = column.Parameters.AddWithValue(operand.Schema); _ = column.Parameters.AddWithValue(operand.Table); _ = column.Parameters.AddWithValue(operand.Column);
        await using var reader = await column.ExecuteReaderAsync(ct);
        Assert.True(await reader.ReadAsync(ct));
        Assert.Equal(operand.AppendOrdinal, reader.GetInt16(0));
        Assert.Equal(operand.PostgreSqlType, reader.GetString(1));
        Assert.Equal(!operand.Nullable, reader.GetBoolean(2));
        Assert.Equal(operand.DefaultExpression is not null, reader.GetBoolean(3));
        if (operand.DefaultExpression is null) { Assert.True(reader.IsDBNull(6)); }
        else { Assert.Equal("false", reader.GetString(6)); }
        Assert.Equal(operand.Nullable ? 0L : 1L, reader.GetInt64(7));
        Assert.False(await reader.ReadAsync(ct));
    }

    private static async Task InsertAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, TableCopyPlan table, int id, CancellationToken ct)
    {
        string[] columns = [.. table.OrderedColumns.Except(table.GeneratedColumns.Select(x => x.Column), StringComparer.Ordinal)];
        string names = string.Join(',', columns.Select(PostgreSqlShadowTarget.QuoteIdentifier));
        string placeholders = string.Join(',', Enumerable.Range(1, columns.Length).Select(x => "$" + x));
        await using var command = new NpgsqlCommand($"INSERT INTO public.{PostgreSqlShadowTarget.QuoteIdentifier(table.TargetTable)} ({names}) VALUES ({placeholders});",
            connection, transaction)
        { CommandTimeout = 30 };
        foreach (string name in columns)
        {
            object? value = table.NullableColumns.Contains(name, StringComparer.Ordinal) ? null : table.ColumnTypes[name] switch
            {
                "integer" => id,
                "boolean" => false,
                "numeric(18,2)" => 1m,
                "timestamp without time zone" => new DateTime(2000, 1, 1, 0, 0, 0, DateTimeKind.Unspecified),
                _ when table.ColumnTypes[name] == "text" || table.ColumnTypes[name].StartsWith("character varying(", StringComparison.Ordinal) => "s" + id + " ไทย  ",
                _ => throw new InvalidOperationException("Unreviewed synthetic seed type."),
            };
            if (name is "PasswordHash" or "Comment")
            {
                value = string.Concat(Enumerable.Range(0, 256).Select(part => Convert.ToHexStringLower(
                    SHA256.HashData(Encoding.UTF8.GetBytes($"synthetic-toast-{id}-{part}"))))) + " ไทย  ";
            }
            _ = command.Parameters.AddWithValue(value ?? DBNull.Value);
        }
        _ = await command.ExecuteNonQueryAsync(ct);
    }

    private static async Task ExecuteAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, string sql, CancellationToken ct)
    {
        await using var command = new NpgsqlCommand(sql, connection, transaction) { CommandTimeout = 30 };
        _ = await command.ExecuteNonQueryAsync(ct);
    }
}
