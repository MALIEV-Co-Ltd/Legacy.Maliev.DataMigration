using System.Data;
using Npgsql;
using Testcontainers.PostgreSql;
using Xunit.Abstractions;

namespace Legacy.Maliev.DataMigration.Tests;

[Collection(LocalSnapshotIoTestGroup.Name)]
public sealed class CurrentAppOwnedV3AdditiveNativeTests(ITestOutputHelper output)
{
    private readonly ITestOutputHelper _output = output;
    private static readonly string[] InvoiceFaults = ["retained-row", "added-nonnull", "default", "type", "ordinal", "added-storage", "extra-object"];
    private static readonly string[] CreateFaults = ["retained-row", "extra-object", "new-row"];

    [Theory]
    [InlineData("Invoice")]
    [InlineData("PurchaseOrder")]
    [InlineData("Quotation")]
    public async Task Fixed_additions_preserve_populated_rows_nulls_private_receipts_and_sequences(string database)
    {
        using var deadline = new CancellationTokenSource(TimeSpan.FromMinutes(4));
        CancellationToken ct = deadline.Token;
        string run = Guid.NewGuid().ToString("N");
        string name = "v3-additive-native-" + run;
        string observedId = "unobserved";
        DateTimeOffset started = DateTimeOffset.UtcNow;
        _output.WriteLine("Resource attempt run={0}; name={1}; persistent=false; expires={2:O}", run, name, started.AddMinutes(5));
        var postgres = new PostgreSqlBuilder("postgres:18.4-bookworm@sha256:882236b897e39051d2368c5ccc6cda944904723506b2dfc97f2a8f5bc9afa382")
            .WithDatabase(database).WithUsername("postgres").WithPassword(Guid.NewGuid().ToString("N"))
            .WithName(name).WithLabel("codex.repair.run", run).WithLabel("codex.repair.purpose", "v3-additive-native-component")
            .WithCreateParameterModifier(parameters =>
            {
                parameters.HostConfig!.Memory = 384 * 1024 * 1024;
                parameters.HostConfig.MemorySwap = 384 * 1024 * 1024;
                parameters.HostConfig.NanoCPUs = 500_000_000;
            }).Build();
        try
        {
            await postgres.StartAsync(ct);
            observedId = postgres.Id;
            _output.WriteLine("Resource observed run={0}; id={1}; port={2}", run, observedId, postgres.GetMappedPublicPort(5432));
            var settings = new NpgsqlConnectionStringBuilder(postgres.GetConnectionString()) { Pooling = false, CommandTimeout = 30 };
            await using var connection = new NpgsqlConnection(settings.ConnectionString);
            await connection.OpenAsync(ct);
            var (before, after) = Pair();
            DatabaseSchemaPlan oldDatabase = before.Databases.Single(x => x.Database == database);
            DatabaseSchemaPlan newDatabase = after.Databases.Single(x => x.Database == database);
            // Fixture-only physical projection; never supplied as an accepted source plan.
            DatabaseSchemaPlan fixture = oldDatabase with
            {
                Tables = ApprovedConsumerColumnOverlayManifest.ComposePhysical(oldDatabase),
                TargetExtensionProfile = null,
                SourceDispositionProfile = null,
                SourceTableDispositions = [],
            };
            await using (var setup = await connection.BeginTransactionAsync(ct))
            {
                await using var inspector = new PostgreSqlWholeDatabaseTransaction(connection, setup, ownsResources: false);
                await inspector.ApplySchemaAsync(fixture, ct); await inspector.FinalizeSchemaAsync(fixture, ct);
                await Sql("""
                    CREATE SCHEMA legacy_migration_internal;
                    CREATE TABLE legacy_migration_internal.receipts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,payload text NOT NULL);
                    INSERT INTO legacy_migration_internal.receipts(payload) VALUES ('immutable sentinel กขค'),('immutable sentinel กขค');
                    SELECT setval(pg_get_serial_sequence('legacy_migration_internal.receipts','id'),91,true);
                    ANALYZE legacy_migration_internal.receipts;
                    COMMENT ON TABLE legacy_migration_internal.receipts IS 'immutable receipt comment';
                    """, setup);
                string root = database == "Quotation" ? "Quotation" : "Probe";
                await Sql($"INSERT INTO public.{Q(root)} (\"ID\",\"Value\") VALUES (1,'ต้นฉบับ กขค 🇹🇭');", setup);
                if (database == "Invoice")
                {
                    await Sql("""
                        INSERT INTO public."InvoiceCreationAdmission" VALUES
                        ('00000000-0000-0000-0000-000000000001',1,'พนักงาน กขค','service:invoice','fingerprint-1','prepared',NULL,'2026-01-01T00:00:00Z','2026-01-01T00:00:00Z'),
                        ('00000000-0000-0000-0000-000000000002',2,'พนักงาน กขค','service:invoice','fingerprint-2','prepared','{"ไทย":"กขค"}','2026-01-01T00:00:00Z','2026-01-01T00:00:00Z');
                        ANALYZE public."InvoiceCreationAdmission";
                        COMMENT ON TABLE public."InvoiceCreationAdmission" IS 'retained admission comment';
                        COMMENT ON COLUMN public."InvoiceCreationAdmission"."ResultJson" IS 'retained nullable result comment';
                        """, setup);
                }
                await setup.CommitAsync(ct);
            }
            V3AdditiveObservation baseline = await Capture(isAfter: false);
            foreach (string fault in database == "Invoice" ? InvoiceFaults : CreateFaults)
            {
                await using var negative = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct);
                await Apply(negative);
                string sql = fault switch
                {
                    "retained-row" => "UPDATE legacy_migration_internal.receipts SET payload='forbidden mutation' WHERE id=1;",
                    "added-nonnull" => "UPDATE public.\"InvoiceCreationAdmission\" SET \"OriginIssuer\"='forbidden backfill';",
                    "default" => "ALTER TABLE public.\"InvoiceCreationAdmission\" ALTER COLUMN \"OriginIssuer\" SET DEFAULT 'forbidden';",
                    "type" => "ALTER TABLE public.\"InvoiceCreationAdmission\" ALTER COLUMN \"OriginIssuer\" TYPE text;",
                    "added-storage" => "ALTER TABLE public.\"InvoiceCreationAdmission\" ALTER COLUMN \"OriginIssuer\" SET STORAGE PLAIN;",
                    "ordinal" => "ALTER TABLE public.\"InvoiceCreationAdmission\" RENAME COLUMN \"FinancialResultJson\" TO \"swap\"; " +
                        "ALTER TABLE public.\"InvoiceCreationAdmission\" RENAME COLUMN \"FinancialOwnershipJson\" TO \"FinancialResultJson\"; " +
                        "ALTER TABLE public.\"InvoiceCreationAdmission\" RENAME COLUMN \"swap\" TO \"FinancialOwnershipJson\";",
                    "new-row" => NewRow(database),
                    _ => "CREATE TABLE legacy_migration_internal.unreviewed(id integer);",
                };
                await Sql(sql, negative);
                _ = await Assert.ThrowsAsync<MigrationExecutionException>(async () =>
                {
                    V3AdditiveObservation observed = await CurrentAppOwnedV3AdditivePreservation.CaptureAsync(connection, negative,
                        before, after, before.SourceCommitSha, true, DateTimeOffset.UtcNow, ct);
                    CurrentAppOwnedV3AdditivePreservation.RequirePreserved(baseline, observed);
                });
                await negative.RollbackAsync(ct);
            }
            await using (var rollback = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                await CurrentAppOwnedRepairPreservation.LockAsync(connection, rollback, baseline.Snapshot, ct);
                await Apply(rollback); await Verify(rollback); await rollback.RollbackAsync(ct);
            }
            Assert.Equal(baseline.Snapshot.Sha256, (await Capture(isAfter: false)).Snapshot.Sha256);
            await using (var commit = await connection.BeginTransactionAsync(IsolationLevel.Serializable, ct))
            {
                await CurrentAppOwnedRepairPreservation.LockAsync(connection, commit, baseline.Snapshot, ct);
                await Apply(commit); await Verify(commit); await commit.CommitAsync(ct);
            }
            CurrentAppOwnedV3AdditivePreservation.RequirePreserved(baseline, await Capture(isAfter: true));

            async Task Apply(NpgsqlTransaction transaction)
            {
                if (database == "Invoice")
                {
                    await Sql("""
                        ALTER TABLE public."InvoiceCreationAdmission" ADD COLUMN "OriginIssuer" character varying(512) COLLATE "C" NULL;
                        ALTER TABLE public."InvoiceCreationAdmission" ADD COLUMN "FinancialResultJson" text COLLATE "C" NULL;
                        ALTER TABLE public."InvoiceCreationAdmission" ADD COLUMN "FinancialOwnershipJson" text COLLATE "C" NULL;
                        ALTER TABLE public."InvoiceCreationAdmission" ADD COLUMN "EmployeeCompletionJson" text COLLATE "C" NULL;
                        """, transaction);
                }
                else
                {
                    DatabaseSchemaPlan additions = newDatabase with
                    {
                        Tables = ApprovedTargetExtensionManifest.TablesFor(newDatabase),
                        TargetExtensionProfile = null,
                        SourceDispositionProfile = null,
                        SourceTableDispositions = [],
                    };
                    await using var inspector = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
                    await inspector.ApplySchemaAsync(additions, ct); await inspector.FinalizeSchemaAsync(additions, ct);
                }
            }
            async Task Verify(NpgsqlTransaction transaction)
            {
                if (database == "Invoice")
                {
                    await using var diagnostic = new NpgsqlCommand("""
                        SELECT jsonb_build_object('ordinal',a.attnum,'name',a.attname,'type',t.typname,'typmod',a.atttypmod,
                            'statisticsTargetIsNull',a.attstattarget IS NULL,'statisticsTarget',a.attstattarget,
                            'nullable',NOT a.attnotnull,'hasDefault',a.atthasdef,'hasMissing',a.atthasmissing,
                            'missingValueIsNull',a.attmissingval IS NULL,'aclIsNull',a.attacl IS NULL,
                            'optionsIsNull',a.attoptions IS NULL,'foreignOptionsIsNull',a.attfdwoptions IS NULL,
                            'isLocal',a.attislocal,'inherited',a.attinhcount,'identity',a.attidentity,'generated',a.attgenerated,
                            'collation',c.collname)::text
                        FROM pg_attribute a JOIN pg_type t ON t.oid=a.atttypid JOIN pg_collation c ON c.oid=a.attcollation
                        WHERE a.attrelid='public."InvoiceCreationAdmission"'::regclass AND a.attnum BETWEEN 10 AND 13 ORDER BY a.attnum;
                        """, connection, transaction);
                    await using NpgsqlDataReader reader = await diagnostic.ExecuteReaderAsync(ct);
                    while (await reader.ReadAsync(ct)) { _output.WriteLine("Approved added-column native metadata: {0}", reader.GetString(0)); }
                }
                V3AdditiveObservation observed = await CurrentAppOwnedV3AdditivePreservation.CaptureAsync(connection, transaction,
                    before, after, before.SourceCommitSha, true, DateTimeOffset.UtcNow, ct);
                CurrentAppOwnedV3AdditivePreservation.RequirePreserved(baseline, observed);
            }
            async Task<V3AdditiveObservation> Capture(bool isAfter)
            {
                await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.RepeatableRead, ct);
                await Sql("SET TRANSACTION READ ONLY;", transaction);
                return await CurrentAppOwnedV3AdditivePreservation.CaptureAsync(connection, transaction,
                    before, after, before.SourceCommitSha, isAfter, DateTimeOffset.UtcNow, ct);
            }
            async Task Sql(string sql, NpgsqlTransaction transaction)
            { await using var command = new NpgsqlCommand(sql, connection, transaction); _ = await command.ExecuteNonQueryAsync(ct); }
        }
        finally
        {
            _output.WriteLine("Resource cleanup requested run={0}; id={1}; name={2}", run, observedId, name);
            await postgres.DisposeAsync().AsTask().WaitAsync(TimeSpan.FromSeconds(30));
            _output.WriteLine("Resource disposed run={0}; id={1}; exact Docker absence requires runner verification", run, observedId);
        }
    }

    private static string Q(string name)
    {
        return PostgreSqlShadowTarget.QuoteIdentifier(name);
    }

    private static string NewRow(string database)
    {
        return database == "PurchaseOrder" ? """
        INSERT INTO public."OrderItemCreateReceipt" VALUES
        (decode(repeat('aa',32),'hex'),decode(repeat('bb',32),'hex'),3,decode(repeat('cc',32),'hex'),1,
         decode(repeat('dd',32),'hex'),1,1,decode('aa','hex'),decode(repeat('ee',32),'hex'),'2026-01-01T00:00:00Z');
        """ : """
        INSERT INTO public."QuotationInvoiceCompletionOperation" VALUES
        ('00000000-0000-0000-0000-000000000001',1,1,'{}','[]','[]','prepared','1','2026-01-01',NULL,NULL);
        """;
    }

    private static (FreshSchemaPlan Before, FreshSchemaPlan After) Pair()
    {
        FreshSchemaPlan before = CurrentConsumerSchemaV2Tests.Schema(ConsumerOverlaySelection.CurrentConsumerSchemaV2) with { CapturedAtUtc = DateTimeOffset.UtcNow };
        before = before with { Databases = [.. before.Databases.Select(x => x.Database == "Quotation" ? Map(x) : x)] };
        FreshSchemaPlan after = before with { Databases = [.. before.Databases.Select(Reprofile)] };
        return (before, after);
        static DatabaseSchemaPlan Reprofile(DatabaseSchemaPlan database)
        {
            database = database with { TargetExtensionProfile = ApprovedConsumerOverlaySelection.ProfileForDatabase(database.Database, ConsumerOverlaySelection.CurrentConsumerSchemaV3) };
            return database with { TargetSchemaSha256 = PostgreSqlSchemaFingerprint.ComputeExpected(database) };
        }
        static DatabaseSchemaPlan Map(DatabaseSchemaPlan database)
        {
            TableCopyPlan[] tables = [database.Tables[0],
                ApprovedSourceDispositionManifestTests.Outbox(CurrentQuotationSourceContract.GoogleAnalyticsOutbox, "PK_GoogleAnalyticsOutbox", "UX_GoogleAnalyticsOutbox_EventKey", uniqueIndex: true),
                ApprovedSourceDispositionManifestTests.Outbox(CurrentQuotationSourceContract.QuotationOutcomeOutbox, "PK_QuotationOutcomeOutbox", "UQ_QuotationOutcomeOutbox_EventKey", uniqueIndex: false), .. database.Tables.Skip(3)];
            database = database with
            {
                Tables = tables,
                SourceDispositionProfile = ApprovedSourceDispositionManifest.QuotationOutboxesV1,
                SourceTableDispositions = ApprovedSourceDispositionManifest.DispositionsForDatabase("Quotation", tables)
            };
            return database with { TargetSchemaSha256 = PostgreSqlSchemaFingerprint.ComputeExpected(database) };
        }
    }
}
