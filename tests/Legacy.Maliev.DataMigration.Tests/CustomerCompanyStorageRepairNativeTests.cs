using System.Data;
using Npgsql;
using Xunit.Abstractions;

namespace Legacy.Maliev.DataMigration.Tests;

/// <summary>Disposable characterization only; no operational catalog-transition verifier or persistent authority.</summary>
[Collection(CompanyStoragePreservationTestGroup.Name)]
public sealed class CustomerCompanyStorageRepairNativeTests(CompanyStoragePreservationFixture fixture, ITestOutputHelper output)
{
    [Fact]
    public async Task Fixed_candidate_preserves_rows_allocations_and_unrelated_objects_with_rollback_and_independent_readback()
    {
        PostgreSqlShadowTarget target = fixture.CreateShadowTarget();
        ShadowDatabase shadow = await target.CreateUniqueEmptyShadowAsync("Customer",
            $"legacy_shadow_company_repair_{Guid.NewGuid():N}", Guid.NewGuid().ToString("D"), default);
        string connectionString = new NpgsqlConnectionStringBuilder(fixture.ConnectionString) { Database = shadow.Name, Pooling = false }.ConnectionString;
        var contract = CustomerCompanyStorageRepairContractTests.Create(
            CustomerCompanyStorageRepairContractTests.Before(), CustomerCompanyStorageRepairContractTests.Owner());
        try
        {
            await using var connection = new NpgsqlConnection(connectionString);
            await connection.OpenAsync();
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
            {
                await using var seed = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
                await seed.ApplySchemaAsync(contract.Before(), default);
                await seed.FinalizeSchemaAsync(contract.Before(), default);
                Assert.Equal(contract.Before().TargetSchemaSha256, await seed.InspectSchemaAsync(contract.Before(), default));
                await ExecuteAsync(connection, transaction, """
                    INSERT INTO public."Company" ("ID","Name","TaxNumber","Registrar")
                        VALUES (100,'preserve trailing spaces  ',NULL,'registrar  '),(101,'second','tax  ',NULL),
                            (102,repeat('😀',128),NULL,NULL);
                    CREATE TABLE public."Unrelated" ("ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Payload" text);
                    INSERT INTO public."Unrelated" ("Payload") VALUES ('unrelated fixture  ');
                    CREATE SCHEMA legacy_migration_internal;
                    CREATE TABLE legacy_migration_internal."PrivateJournal" ("ID" integer PRIMARY KEY, "Payload" text);
                    INSERT INTO legacy_migration_internal."PrivateJournal" VALUES (7,'private fixture  ');
                    """);
                await transaction.CommitAsync();
            }
            // The unrelated table is deliberately outside the signed application inventory, so the
            // ordinary full fingerprint is compared before adding it, then with the explicit full fixture inventory.
            CurrentAppOwnedDatabaseSnapshot before = await CaptureAsync(connection);
            string unrelatedBefore = await UnrelatedCatalogAsync(connection);
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
            {
                await ExecuteAsync(connection, transaction, ApprovedCustomerCompanyStorageRepair.CandidateSql);
                CurrentAppOwnedDatabaseSnapshot prepared = await CurrentAppOwnedRepairPreservation.CaptureAsync(connection, transaction, default);
                Assert.Equal(before.Relations, prepared.Relations);
                Assert.Equal(before.Sequences, prepared.Sequences);
                await CustomerCompanyStorageManifest.RequireNormalizerAsync(contract.After(), connection, transaction, default);
                ReportCatalogChanges(before, prepared);
                await transaction.RollbackAsync();
            }
            Assert.Equal(before.Sha256, (await CaptureAsync(connection)).Sha256);
            Assert.Equal(unrelatedBefore, await UnrelatedCatalogAsync(connection));
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
            {
                await ExecuteAsync(connection, transaction, ApprovedCustomerCompanyStorageRepair.CandidateSql);
                CurrentAppOwnedDatabaseSnapshot prepared = await CurrentAppOwnedRepairPreservation.CaptureAsync(connection, transaction, default);
                Assert.Equal(before.Relations, prepared.Relations);
                Assert.Equal(before.Sequences, prepared.Sequences);
                await transaction.CommitAsync();
            }
            await connection.CloseAsync();
            await using var readback = new NpgsqlConnection(connectionString);
            await readback.OpenAsync();
            CurrentAppOwnedDatabaseSnapshot after = await CaptureAsync(readback);
            Assert.Equal(before.Relations, after.Relations);
            Assert.Equal(before.Sequences, after.Sequences);
            Assert.Equal(unrelatedBefore, await UnrelatedCatalogAsync(readback));
            // Inspect the actual full physical inventory, including the deliberately unrelated fixture.
            DatabaseSchemaPlan inspected = contract.After();
            TableCopyPlan unrelated = new("target-only", "Unrelated", "public", "Unrelated", ["ID", "Payload"], ["ID"])
            {
                ColumnTypes = new Dictionary<string, string> { ["ID"] = "integer", ["Payload"] = "text" },
                NullableColumns = ["Payload"],
                PrimaryKey = new("Unrelated_pkey", ["ID"]),
                Identities = [new("ID", 1, 1, 1, true)],
            };
            inspected = inspected with { Tables = [.. inspected.Tables, unrelated] };
            inspected = inspected with { TargetSchemaSha256 = PostgreSqlSchemaFingerprint.ComputeExpected(inspected) };
            await using (var transaction = await readback.BeginTransactionAsync(IsolationLevel.RepeatableRead))
            {
                await using var inspector = new PostgreSqlWholeDatabaseTransaction(readback, transaction, ownsResources: false);
                Assert.Equal(inspected.TargetSchemaSha256, await inspector.InspectSchemaAsync(inspected, default));
                await transaction.RollbackAsync();
            }
        }
        finally { await target.DeleteRunOwnedShadowAsync(shadow, default); }
    }

    [Theory]
    [InlineData("row-limit")]
    [InlineData("utf16-capacity")]
    [InlineData("default")]
    [InlineData("existing-normalizer")]
    public async Task Owner_preconditions_reject_before_conversion_and_rollback_exactly(string fault)
    {
        PostgreSqlShadowTarget target = fixture.CreateShadowTarget();
        ShadowDatabase shadow = await target.CreateUniqueEmptyShadowAsync("Customer",
            $"legacy_shadow_company_guard_{Guid.NewGuid():N}", Guid.NewGuid().ToString("D"), default);
        string connectionString = new NpgsqlConnectionStringBuilder(fixture.ConnectionString) { Database = shadow.Name, Pooling = false }.ConnectionString;
        try
        {
            await using var connection = new NpgsqlConnection(connectionString);
            await connection.OpenAsync();
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
            {
                DatabaseSchemaPlan before = CustomerCompanyStorageRepairContractTests.Before();
                await using var seed = new PostgreSqlWholeDatabaseTransaction(connection, transaction, ownsResources: false);
                await seed.ApplySchemaAsync(before, default);
                await seed.FinalizeSchemaAsync(before, default);
                string sql = fault switch
                {
                    "row-limit" => """INSERT INTO public."Company" ("ID","Name") SELECT value,'row' FROM generate_series(1,10001) value;""",
                    "utf16-capacity" => """INSERT INTO public."Company" ("ID","Name") VALUES (1,repeat('😀',129));""",
                    "default" => """ALTER TABLE public."Company" ALTER COLUMN "Name" SET DEFAULT 'invented';""",
                    _ => """CREATE FUNCTION public."NormalizeCompanySource"() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END;$$;""",
                };
                await ExecuteAsync(connection, transaction, sql);
                await transaction.CommitAsync();
            }
            CurrentAppOwnedDatabaseSnapshot beforeFault = await CaptureAsync(connection);
            await using (var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable))
            {
                PostgresException error = await Assert.ThrowsAsync<PostgresException>(() =>
                    ExecuteAsync(connection, transaction, ApprovedCustomerCompanyStorageRepair.CandidateSql));
                Assert.Equal(PostgresErrorCodes.RaiseException, error.SqlState);
                await transaction.RollbackAsync();
            }
            Assert.Equal(beforeFault.Sha256, (await CaptureAsync(connection)).Sha256);
        }
        finally { await target.DeleteRunOwnedShadowAsync(shadow, default); }
    }

    private void ReportCatalogChanges(CurrentAppOwnedDatabaseSnapshot before, CurrentAppOwnedDatabaseSnapshot after)
    {
        // Report every changed fact's catalog and multiplicity; no tuple values or broad allowlist.
        foreach (string catalog in before.Catalog.Concat(after.Catalog).Select(x => x.Catalog).Distinct().Order(StringComparer.Ordinal))
        {
            int removed = before.Catalog.Where(x => x.Catalog == catalog).Except(after.Catalog).Count();
            int added = after.Catalog.Where(x => x.Catalog == catalog).Except(before.Catalog).Count();
            if (removed != 0 || added != 0) { output.WriteLine($"{catalog}: removed={removed}; added={added}"); }
        }
    }

    private static async Task<CurrentAppOwnedDatabaseSnapshot> CaptureAsync(NpgsqlConnection connection)
    {
        await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.RepeatableRead);
        CurrentAppOwnedDatabaseSnapshot result = await CurrentAppOwnedRepairPreservation.CaptureAsync(connection, transaction, default);
        await transaction.RollbackAsync();
        return result;
    }

    private static async Task<string> UnrelatedCatalogAsync(NpgsqlConnection connection)
    {
        const string sql = """
            WITH relations AS (
                SELECT oid FROM pg_class WHERE oid IN ('public."Unrelated"'::regclass,'legacy_migration_internal."PrivateJournal"'::regclass)
            ), objects AS (
                SELECT c.oid FROM pg_class c WHERE c.oid IN (SELECT oid FROM relations)
                    OR c.oid IN (SELECT indexrelid FROM pg_index WHERE indrelid IN (SELECT oid FROM relations))
            )
            SELECT jsonb_build_object(
                'class',(SELECT jsonb_agg(to_jsonb(c) ORDER BY c.oid) FROM pg_class c WHERE c.oid IN (SELECT oid FROM objects)),
                'attribute',(SELECT jsonb_agg(to_jsonb(a) ORDER BY a.attrelid,a.attnum) FROM pg_attribute a WHERE a.attrelid IN (SELECT oid FROM objects)),
                'index',(SELECT jsonb_agg(to_jsonb(i) ORDER BY i.indexrelid) FROM pg_index i WHERE i.indrelid IN (SELECT oid FROM relations)),
                'constraint',(SELECT jsonb_agg(to_jsonb(k) ORDER BY k.oid) FROM pg_constraint k WHERE k.conrelid IN (SELECT oid FROM relations)))::text;
            """;
        await using var command = new NpgsqlCommand(sql, connection);
        return (string)(await command.ExecuteScalarAsync() ?? throw new InvalidOperationException("Missing fixture catalog."));
    }

    private static async Task ExecuteAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, string sql)
    {
        await using var command = new NpgsqlCommand(sql, connection, transaction);
        _ = await command.ExecuteNonQueryAsync();
    }
}
